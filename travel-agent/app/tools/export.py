"""
Export utilities — generate downloadable Markdown and PDF trip plans.
"""

from __future__ import annotations

import io
import re
from typing import Any

from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer


def generate_markdown(state: dict[str, Any]) -> str:
    """Generate a clean markdown representation of the trip plan."""
    constraints = state.get("trip_constraints", {})
    dest = constraints.get("destination", "Trip")
    duration = constraints.get("duration_days", "")
    
    parts = [f"# ✈️ Travel Itinerary: {dest} ({duration} Days)\n"]
    
    final = state.get("final_response", "")
    itinerary = state.get("itinerary_plan", "")
    
    if final:
        parts.append(final)
    elif itinerary:
        parts.append(itinerary)
    
    budget = state.get("budget_analysis", {})
    if budget:
        parts.append("\n## 💰 Budget Breakdown")
        parts.append(f"- Flights: ₹{budget.get('flights', 0):,.0f}")
        parts.append(f"- Hotels: ₹{budget.get('hotels', 0):,.0f}")
        parts.append(f"- Local Transport: ₹{budget.get('transport', 0):,.0f}")
        parts.append(f"- Food & Dining: ₹{budget.get('food', 0):,.0f}")
        parts.append(f"- Activities: ₹{budget.get('activities', 0):,.0f}")
        parts.append(f"- Buffer / Misc: ₹{budget.get('miscellaneous', 0):,.0f}")
        parts.append(f"**Total Estimated:** ₹{budget.get('estimated_total', 0):,.0f}")
        if budget.get("user_budget"):
            parts.append(f"**User Budget:** ₹{budget.get('user_budget', 0):,.0f}")
    
    parts.append("\n---\n*Generated by AI Travel Planner • Local & Zero-Cost*")
    return "\n".join(parts)


def generate_pdf(state: dict[str, Any]) -> bytes:
    """Generate a styled PDF document of the trip plan using ReportLab."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )
    
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "TripTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=22,
        leading=26,
        textColor=HexColor("#4F46E5"),
        spaceAfter=10,
    )
    heading_style = ParagraphStyle(
        "TripHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=HexColor("#1F2937"),
        spaceBefore=12,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "TripBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=HexColor("#374151"),
        spaceAfter=4,
    )
    meta_style = ParagraphStyle(
        "TripMeta",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=9,
        leading=12,
        textColor=HexColor("#6B7280"),
    )

    story = []
    
    constraints = state.get("trip_constraints", {})
    dest = constraints.get("destination", "Destination")
    duration = constraints.get("duration_days", "")
    
    story.append(Paragraph(f"✈️ Travel Plan: {dest}", title_style))
    story.append(Paragraph(f"Duration: {duration} Days | Dates: {constraints.get('start_date', 'N/A')} to {constraints.get('end_date', 'N/A')}", meta_style))
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=1, color=HexColor("#E5E7EB"), spaceAfter=12))
    
    content = state.get("final_response") or state.get("itinerary_plan", "")
    
    # Simple line-by-line markdown to reportlab converter
    for line in content.split("\n"):
        line = line.strip()
        if not line:
            story.append(Spacer(1, 4))
            continue
        
        # Clean markdown headers
        if line.startswith("#"):
            clean_text = line.lstrip("# ").strip()
            # Remove any asterisks or formatting
            clean_text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", clean_text)
            story.append(Paragraph(clean_text, heading_style))
        elif line.startswith("- ") or line.startswith("* "):
            bullet_text = line[2:].strip()
            bullet_text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", bullet_text)
            story.append(Paragraph(f"• {bullet_text}", body_style))
        else:
            text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", line)
            story.append(Paragraph(text, body_style))
            
    budget = state.get("budget_analysis", {})
    if budget:
        story.append(Spacer(1, 10))
        story.append(Paragraph("Budget Summary", heading_style))
        story.append(Paragraph(f"• Total Estimated: ₹{budget.get('estimated_total', 0):,.0f}", body_style))
        if budget.get("user_budget"):
            story.append(Paragraph(f"• Target Budget: ₹{budget.get('user_budget', 0):,.0f}", body_style))
        story.append(Paragraph(f"• Flights: ₹{budget.get('flights', 0):,.0f} | Hotels: ₹{budget.get('hotels', 0):,.0f} | Local: ₹{budget.get('transport', 0):,.0f}", meta_style))

    story.append(Spacer(1, 15))
    story.append(HRFlowable(width="100%", thickness=0.5, color=HexColor("#9CA3AF"), spaceAfter=8))
    story.append(Paragraph("Generated by Local AI Travel Planner • Zero-Cost Local-First Architecture", meta_style))

    doc.build(story)
    return buffer.getvalue()
